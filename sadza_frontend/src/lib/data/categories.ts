/**
 * Filter categories based on user search term.
 * Matches category name, description, and keyword aliases.
 */
export function filterCategories(query: string): IndustryCategory[] {
  const cleanQuery = query.trim().toLowerCase();
  if (!cleanQuery) {
    return INDUSTRY_CATEGORIES;
  }

  return INDUSTRY_CATEGORIES.filter((category) => {
    // Check direct name match
    if (category.name.toLowerCase().includes(cleanQuery)) {
      return true;
    }
    // Check description match
    if (category.description.toLowerCase().includes(cleanQuery)) {
      return true;
    }
    // Check keywords / aliases match
    return category.keywords.some((kw) => kw.toLowerCase().includes(cleanQuery));
  });
}

/**
 * Find category by exact name or ID.
 */
export function findCategoryByName(name: string): IndustryCategory | undefined {
  return INDUSTRY_CATEGORIES.find(
    (c) => c.name.toLowerCase() === name.toLowerCase() || c.id === name
  );
}
