'use client';

import React, { useState, useRef, useEffect, useId } from 'react';
import { Search, ChevronDown, Check, X, Globe } from 'lucide-react';
import { ALL_COUNTRIES, CountryDialInfo, filterCountries } from '@/lib/data/countries';

export interface CountryCodeSelectProps {
  value: string; // The selected dial code, e.g. '+263'
  onChange: (dialCode: string, country: CountryDialInfo) => void;
  disabled?: boolean;
  className?: string;
  id?: string;
}

export function CountryCodeSelect({
  value,
  onChange,
  disabled = false,
  className = '',
  id,
}: CountryCodeSelectProps) {
  const [isOpen, setIsOpen] = useState(false);
  const [searchQuery, setSearchQuery] = useState('');
  const [highlightedIndex, setHighlightedIndex] = useState(0);

  const containerRef = useRef<HTMLDivElement>(null);
  const searchInputRef = useRef<HTMLInputElement>(null);
  const listRef = useRef<HTMLDivElement>(null);
  const autoGeneratedId = useId();
  const selectId = id || autoGeneratedId;

  // Selected country object based on current value (fallback to Zimbabwe +263)
  const selectedCountry =
    ALL_COUNTRIES.find((c) => c.dialCode === value) ||
    ALL_COUNTRIES[0];

  // Filtered countries based on search query
  const filteredCountries = filterCountries(searchQuery);

  // Close dropdown on click outside
  useEffect(() => {
    function handleClickOutside(event: MouseEvent) {
      if (
        containerRef.current &&
        !containerRef.current.contains(event.target as Node)
      ) {
        setIsOpen(false);
      }
    }
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  // When opening dropdown: focus search input, reset search query and highlighted index
  useEffect(() => {
    if (isOpen) {
      setSearchQuery('');
      // Find the index of the currently selected country in ALL_COUNTRIES
      const currentIndex = ALL_COUNTRIES.findIndex((c) => c.dialCode === value);
      setHighlightedIndex(currentIndex >= 0 ? currentIndex : 0);

      // Auto-focus search input with small timeout for smooth DOM transition
      const timer = setTimeout(() => {
        searchInputRef.current?.focus();
      }, 50);
      return () => clearTimeout(timer);
    }
  }, [isOpen, value]);

  // Ensure highlighted element is scrolled into view
  useEffect(() => {
    if (isOpen && listRef.current) {
      const activeEl = listRef.current.querySelector(
        `[data-index="${highlightedIndex}"]`
      ) as HTMLElement | null;
      if (activeEl) {
        activeEl.scrollIntoView({ block: 'nearest' });
      }
    }
  }, [highlightedIndex, isOpen]);

  const handleSelect = (country: CountryDialInfo) => {
    onChange(country.dialCode, country);
    setIsOpen(false);
  };

  const handleKeyDown = (e: React.KeyboardEvent) => {
    if (!isOpen) {
      if (e.key === 'Enter' || e.key === ' ' || e.key === 'ArrowDown') {
        e.preventDefault();
        setIsOpen(true);
      }
      return;
    }

    switch (e.key) {
      case 'ArrowDown':
        e.preventDefault();
        setHighlightedIndex((prev) =>
          prev < filteredCountries.length - 1 ? prev + 1 : 0
        );
        break;
      case 'ArrowUp':
        e.preventDefault();
        setHighlightedIndex((prev) =>
          prev > 0 ? prev - 1 : filteredCountries.length - 1
        );
        break;
      case 'Enter':
        e.preventDefault();
        if (filteredCountries[highlightedIndex]) {
          handleSelect(filteredCountries[highlightedIndex]);
        }
        break;
      case 'Escape':
        e.preventDefault();
        setIsOpen(false);
        break;
      default:
        break;
    }
  };

  return (
    <div
      ref={containerRef}
      className={`relative inline-block text-left ${className}`}
      onKeyDown={handleKeyDown}
    >
      {/* Trigger Button */}
      <button
        type="button"
        id={selectId}
        disabled={disabled}
        onClick={() => !disabled && setIsOpen((prev) => !prev)}
        aria-haspopup="listbox"
        aria-expanded={isOpen}
        aria-label="Select country calling code"
        className="flex items-center gap-1.5 pl-3 pr-2.5 py-2.5 text-xs font-semibold text-slate-800 dark:text-slate-100 hover:text-slate-900 dark:hover:text-white transition-colors focus:outline-none cursor-pointer disabled:opacity-50 disabled:cursor-not-allowed select-none"
      >
        <span className="text-base leading-none select-none" aria-hidden="true">
          {selectedCountry.flag}
        </span>
        <span className="font-mono tracking-tight font-bold">
          {selectedCountry.dialCode}
        </span>
        <ChevronDown
          className={`h-3 w-3 text-slate-400 dark:text-slate-500 transition-transform duration-200 ${
            isOpen ? 'rotate-180 text-emerald-600 dark:text-emerald-400' : ''
          }`}
        />
      </button>

      {/* Popover Dropdown */}
      {isOpen && (
        <div
          role="dialog"
          aria-label="Country calling code search"
          className="absolute left-0 top-[calc(100%+6px)] z-50 w-72 sm:w-80 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-2xl overflow-hidden animate-in fade-in zoom-in-95 duration-150"
        >
          {/* Search Bar Input */}
          <div className="p-2.5 border-b border-slate-100 dark:border-slate-800/80 bg-slate-50/70 dark:bg-slate-950/60">
            <div className="relative flex items-center">
              <Search className="pointer-events-none absolute left-3 h-3.5 w-3.5 text-slate-400 dark:text-slate-500" />
              <input
                ref={searchInputRef}
                type="text"
                value={searchQuery}
                onChange={(e) => {
                  setSearchQuery(e.target.value);
                  setHighlightedIndex(0);
                }}
                placeholder="Search country or code (e.g. 234, Nigeria)..."
                className="w-full rounded-xl border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 pl-8 pr-7 py-2 text-xs text-slate-900 dark:text-white placeholder:text-slate-400 dark:placeholder:text-slate-500 focus:outline-none focus:border-emerald-500 dark:focus:border-emerald-400 focus:ring-1 focus:ring-emerald-500/20 font-medium"
              />
              {searchQuery && (
                <button
                  type="button"
                  onClick={() => {
                    setSearchQuery('');
                    setHighlightedIndex(0);
                    searchInputRef.current?.focus();
                  }}
                  className="absolute right-2 p-1 text-slate-400 hover:text-slate-600 dark:hover:text-slate-300"
                  aria-label="Clear search query"
                >
                  <X className="h-3 w-3" />
                </button>
              )}
            </div>
          </div>

          {/* Country List */}
          <div
            ref={listRef}
            role="listbox"
            tabIndex={-1}
            className="max-h-60 overflow-y-auto divide-y divide-slate-100 dark:divide-slate-800/50 overscroll-contain py-1"
          >
            {filteredCountries.length > 0 ? (
              filteredCountries.map((country, index) => {
                const isSelected = country.dialCode === value;
                const isHighlighted = index === highlightedIndex;

                return (
                  <div
                    key={`${country.code}-${country.dialCode}-${index}`}
                    data-index={index}
                    role="option"
                    aria-selected={isSelected}
                    onClick={() => handleSelect(country)}
                    onMouseEnter={() => setHighlightedIndex(index)}
                    className={`flex items-center justify-between px-3.5 py-2 text-xs cursor-pointer transition-colors ${
                      isHighlighted
                        ? 'bg-emerald-50 dark:bg-emerald-950/40 text-slate-900 dark:text-white'
                        : isSelected
                        ? 'bg-slate-50 dark:bg-slate-800/50 text-slate-900 dark:text-white'
                        : 'text-slate-700 dark:text-slate-300 hover:bg-slate-50 dark:hover:bg-slate-800/40'
                    }`}
                  >
                    <div className="flex items-center gap-2.5 min-w-0 pr-2">
                      <span className="text-base leading-none select-none shrink-0" aria-hidden="true">
                        {country.flag}
                      </span>
                      <span className="truncate font-medium">
                        {country.name}
                      </span>
                      <span className="text-[10px] uppercase tracking-wider font-semibold text-slate-400 dark:text-slate-500 shrink-0">
                        ({country.code})
                      </span>
                    </div>

                    <div className="flex items-center gap-1.5 shrink-0 pl-2">
                      <span className="font-mono font-bold text-slate-600 dark:text-slate-300 text-[11px]">
                        {country.dialCode}
                      </span>
                      {isSelected && (
                        <Check className="h-3.5 w-3.5 text-emerald-600 dark:text-emerald-400 shrink-0" />
                      )}
                    </div>
                  </div>
                );
              })
            ) : (
              <div className="py-6 px-4 text-center">
                <Globe className="mx-auto h-6 w-6 text-slate-300 dark:text-slate-600 mb-1.5" />
                <p className="text-xs font-semibold text-slate-700 dark:text-slate-300">
                  No matching country
                </p>
                <p className="text-[11px] text-slate-500 dark:text-slate-400 mt-0.5">
                  Try typing the country name or calling code digits (e.g. 234 or Nigeria)
                </p>
              </div>
            )}
          </div>

          {/* Quick Counter Footer */}
          <div className="px-3 py-1.5 bg-slate-50 dark:bg-slate-950/80 border-t border-slate-100 dark:border-slate-800/80 flex items-center justify-between text-[10px] text-slate-500 dark:text-slate-400 font-medium">
            <span>
              {filteredCountries.length} {filteredCountries.length === 1 ? 'country' : 'countries'}
            </span>
            <span className="text-slate-400">Use ↑↓ arrows to navigate</span>
          </div>
        </div>
      )}
    </div>
  );
}
